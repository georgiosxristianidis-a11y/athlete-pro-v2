/* ════════════════════════════════════════════════════════
   tap-gesture.js — UX-2j: N тапов подряд за окно времени
   ────────────────────────────────────────────────────────
   Скрытый жест (5 тапов по строке версии открывают Лабораторию). Чистая
   функция без DOM: время приходит снаружи, поэтому тест гоняет её без
   таймеров. Окно скользящее — каждый тап должен прийти не позже `windowMs`
   после предыдущего; пауза длиннее обнуляет счёт.
   ════════════════════════════════════════════════════════ */

/**
 * @param {number} count сколько тапов открывает жест
 * @param {number} windowMs максимальная пауза между соседними тапами
 * @returns {(now?: number) => boolean} вызывать на каждый тап; true — жест сработал
 */
export function createTapGesture(count, windowMs) {
  let taps = 0;
  let last = 0;
  return (now = Date.now()) => {
    taps = taps > 0 && now - last <= windowMs ? taps + 1 : 1;
    last = now;
    if (taps < count) return false;
    taps = 0;
    return true;
  };
}
