/* UX-1c (аудит 14.11, находки №3 и половина №10): вес подхода не переходил на
   следующие — 60 в первом, второй и третий оставались 0, а «+ Подход» копировал
   этот 0. Норма журналов: следующий подход наследует вес. Здесь правило без DOM:
   поставленный рукой вес протягивается вниз по подряд идущим незакрытым подходам,
   которых рука ещё не касалась. Закрытый подход — факт, тронутый — решение
   пользователя: на первом таком протяжка останавливается. Значение берётся
   ровно то, что записано в исходный подход, — оно уже на сетке барабана этого
   упражнения, значит показанное в нижних строках совпадёт с записанным. */

/**
 * Пометить подход `si` тронутым и протянуть его вес вниз.
 * @param {Array<{weight?: number, done?: boolean, wSet?: boolean}>} sets — подходы упражнения, правятся на месте
 * @param {number} si — подход, которому только что поставили вес
 * @returns {number[]} индексы подходов, чей вес сменился
 */
export function fillWeightDown(sets, si) {
  const src = sets?.[si];
  if (!src) return [];
  src.wSet = true;
  const changed = [];
  for (let i = si + 1; i < sets.length; i++) {
    const s = sets[i];
    if (!s || s.done || s.wSet) break;
    if (s.weight !== src.weight) {
      s.weight = src.weight;
      changed.push(i);
    }
  }
  return changed;
}
