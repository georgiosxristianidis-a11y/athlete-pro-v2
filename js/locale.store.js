let _lang = 'en';

/**
 * First-run language from the device locale list. UI code still reads
 * `getLang()` / `isRu()` / `t()` — not `navigator.language`.
 * Only the primary tag is consulted; anything other than `ru*` stays `en`.
 * @param {readonly string[] | undefined} [languages]
 * @returns {'en'|'ru'}
 */
export function detectDeviceLang(languages) {
  const tags = Array.isArray(languages)
    ? languages
    : typeof navigator !== 'undefined'
      ? navigator.languages?.length
        ? [...navigator.languages]
        : navigator.language
          ? [navigator.language]
          : []
      : [];
  const primary = String(tags[0] || '')
    .trim()
    .toLowerCase()
    .split(/[-_]/)[0];
  return primary === 'ru' ? 'ru' : 'en';
}

/**
 * Initialize locale from saved settings, or persist a device-locale default
 * when the user has never chosen a language (LAUNCH-5B / F-1).
 */
export async function initLocale() {
  const saved = await DB.Settings.get('lang');
  if (saved === 'ru' || saved === 'en') {
    _lang = saved;
    return;
  }
  _lang = detectDeviceLang();
  await DB.Settings.set('lang', _lang);
}

/**
 * Get current language.
 */
export function getLang() {
  return _lang;
}

/**
 * Whether the app language (NOT the browser/OS language) is Russian.
 * Single source of truth for `ru ? … : …` ternaries across the UI.
 * @returns {boolean}
 */
export function isRu() {
  return _lang === 'ru';
}

/**
 * Set language.
 * @param {'en'|'ru'} lang
 */
export async function setLang(lang) {
  _lang = lang;
  await DB.Settings.set('lang', lang);
  window.dispatchEvent(new CustomEvent('ap-locale-change', { detail: { lang } }));
}

/**
 * Translate a key.
 * @param {string} key
 * @param {Object} [params]
 * @returns {string}
 */
export function t(key, params = {}) {
  let str = DICT[_lang]?.[key] || DICT['en']?.[key] || key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replace(`{${k}}`, v);
  }
  return str;
}
